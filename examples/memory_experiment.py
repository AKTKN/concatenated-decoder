"""Memory experiment example using concat-decoder decoders.

Demonstrates how to use the concat-decoder package as an external library to run a
Z-memory experiment on a midout color code circuit generated by Chromobius.

Circuit file
------------
The stim circuit under `circuits/` was created by Chromobius and contains
DETECTOR annotations whose 4th coordinate encodes color and basis information:

    0: red X     3: red Z
    1: green X   4: green Z
    2: blue X    5: blue Z
   -1: ignore this detector (e.g. from a non-color-code region)

concat-decoder reads these annotations automatically via
`concat_decoder.dem.model.parse_detector_metadata` when you construct a decoder.

Usage
-----
    python examples/memory_experiment.py

Requirements
------------
    pip install stim pymatching beliefmatching
    pip install -e .          # install concat-decoder itself from the repo root
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import numpy as np
import stim

import concat_decoder
from concat_decoder import DecoderConfig

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

REPO_ROOT = Path(__file__).resolve().parent.parent
CIRCUITS_DIR = REPO_ROOT / "circuits"

DEFAULT_CIRCUIT = (
    CIRCUITS_DIR
    / "code=midout_color_code_Z,d=5,rounds=5,noisemodel=uniform,p=0.001.stim"
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _print_circuit_info(circuit: stim.Circuit) -> None:
    coords = circuit.get_detector_coordinates()
    coord4_counts: dict[int, int] = {}
    for c in coords.values():
        if len(c) >= 4:
            k = int(round(c[3]))
            coord4_counts[k] = coord4_counts.get(k, 0) + 1

    chromobius_label = {
        0: "rX", 1: "gX", 2: "bX",
        3: "rZ", 4: "gZ", 5: "bZ",
        -1: "ignore",
    }
    summary = ", ".join(
        f"{chromobius_label.get(k, str(k))}×{n}"
        for k, n in sorted(coord4_counts.items())
    )
    print(f"  Qubits:      {circuit.num_qubits}")
    print(f"  Detectors:   {circuit.num_detectors}  [{summary}]")
    print(f"  Observables: {circuit.num_observables}")


def _run_and_report(
    label: str,
    decoder,
    sampler,
    shots: int,
) -> None:
    det_outcomes, obs_true = sampler.sample(
        shots=shots, separate_observables=True, bit_packed=False
    )

    t0 = time.perf_counter()
    obs_pred = decoder.decode_batch(det_outcomes)
    elapsed = time.perf_counter() - t0

    obs_pred_u8 = np.asarray(obs_pred, dtype=np.uint8)
    obs_true_u8 = np.asarray(obs_true, dtype=np.uint8)
    mismatch = (obs_pred_u8 != obs_true_u8).any(axis=1)
    errors = int(mismatch.sum())
    ler = float(errors) / shots

    ms_per_shot = elapsed / shots * 1_000
    print(f"  [{label}]")
    print(f"    shots          : {shots}")
    print(f"    logical errors : {errors}")
    print(f"    LER            : {ler:.4%}")
    print(f"    decode time    : {elapsed:.3f}s  ({ms_per_shot:.3f} ms/shot)")


# ---------------------------------------------------------------------------
# Main experiment
# ---------------------------------------------------------------------------


def run_memory_experiment(circuit_path: Path, shots: int, seed: int) -> None:
    print(f"Circuit: {circuit_path.name}")
    circuit = stim.Circuit.from_file(str(circuit_path))
    _print_circuit_info(circuit)
    print()

    # Both decoders accept any stim.Circuit whose DETECTORs carry the
    # Chromobius 4th-coordinate annotation (or the color-code-stim 5-coordinate
    # variant).  The mapping is parsed internally; no extra configuration is
    # needed beyond optionally passing a DecoderConfig.
    mwpm_decoder = concat_decoder.ConcatMWPMDecoder(circuit)
    bp_decoder = concat_decoder.ConcatBPMatchingDecoder(circuit)

    sampler = circuit.compile_detector_sampler(seed=seed)

    print(f"Shots: {shots}  Seed: {seed}")
    print()
    _run_and_report("ConcatMWPMDecoder    ", mwpm_decoder, sampler, shots)
    print()

    # Re-create the sampler so both decoders see identical shot data.
    sampler = circuit.compile_detector_sampler(seed=seed)
    _run_and_report("ConcatBPMatchingDecoder", bp_decoder, sampler, shots)


# ---------------------------------------------------------------------------
# Multi-noise sweep (optional)
# ---------------------------------------------------------------------------


def _build_circuit_at_noise(
    base_circuit: stim.Circuit,
    p: float,
) -> stim.Circuit:
    """Rescale every X/Z/DEPOLARIZE error instruction to probability *p*.

    This is a simple rescaling that works for circuits whose error instructions
    were generated with a single noise parameter.  For production use prefer
    regenerating the circuit with Chromobius at the desired p.
    """
    lines = str(base_circuit).splitlines()
    rescaled: list[str] = []
    error_prefixes = (
        "X_ERROR(", "Z_ERROR(", "DEPOLARIZE1(", "DEPOLARIZE2(",
        "PAULI_CHANNEL_1(", "PAULI_CHANNEL_2(", "ELSE_CORRELATED_ERROR(",
        "CORRELATED_ERROR(",
    )
    import re
    pattern = re.compile(r"^(\s*\w[\w_]*)\(([^)]+)\)(.*)")

    for line in lines:
        stripped = line.lstrip()
        match = pattern.match(line)
        if match and any(stripped.startswith(ep) for ep in error_prefixes):
            # Replace the probability argument with the new p.
            rescaled.append(f"{match.group(1)}({p}){match.group(3)}")
        else:
            rescaled.append(line)
    return stim.Circuit("\n".join(rescaled))


def run_noise_sweep(
    circuit_path: Path,
    p_values: list[float],
    shots: int,
    seed: int,
) -> None:
    print(f"Noise sweep on: {circuit_path.name}")
    print(f"{'p':>10}  {'LER (ConcatMWPM)':>20}  {'LER (ConcatBP→MWPM)':>22}")
    print("-" * 58)

    base_circuit = stim.Circuit.from_file(str(circuit_path))

    for p in p_values:
        circuit = _build_circuit_at_noise(base_circuit, p)

        mwpm_dec = concat_decoder.ConcatMWPMDecoder(circuit)
        bp_dec = concat_decoder.ConcatBPMatchingDecoder(circuit)

        sampler_m = circuit.compile_detector_sampler(seed=seed)
        sampler_b = circuit.compile_detector_sampler(seed=seed)

        det_m, obs_m = sampler_m.sample(shots=shots, separate_observables=True, bit_packed=False)
        det_b, obs_b = sampler_b.sample(shots=shots, separate_observables=True, bit_packed=False)

        pred_m = np.asarray(mwpm_dec.decode_batch(det_m), dtype=np.uint8)
        pred_b = np.asarray(bp_dec.decode_batch(det_b), dtype=np.uint8)

        ler_m = float((pred_m != np.asarray(obs_m, dtype=np.uint8)).any(axis=1).mean())
        ler_b = float((pred_b != np.asarray(obs_b, dtype=np.uint8)).any(axis=1).mean())

        print(f"{p:>10.4f}  {ler_m:>20.4%}  {ler_b:>22.4%}")


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="concat-decoder memory experiment example",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--circuit",
        type=Path,
        default=DEFAULT_CIRCUIT,
        help="Path to a .stim circuit file with Chromobius-style DETECTOR coords",
    )
    parser.add_argument("--shots", type=int, default=10_000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--sweep",
        action="store_true",
        help="Run a noise-level sweep instead of a single-p experiment",
    )
    parser.add_argument(
        "--p-values",
        nargs="+",
        type=float,
        default=[0.005, 0.001, 0.0005, 0.0001],
        metavar="P",
        help="Noise probability values for --sweep",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = _parse_args()

    if args.sweep:
        run_noise_sweep(args.circuit, args.p_values, args.shots, args.seed)
    else:
        run_memory_experiment(args.circuit, args.shots, args.seed)
